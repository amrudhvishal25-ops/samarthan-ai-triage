export function formatUpdateConfirmation(
  lang: SupportedLanguage,
  incidentId: string,
  filledItems: string[],
  trackingLink: string
): string {
  const isHi = lang === 'hi'
  const isEn = lang === 'en'

  if (filledItems.length > 0) {
    if (isHi) {
      return `✅ *शिकायत (${incidentId}) में विवरण स्वतः जोड़ दिया गया!*
📌 *घटना आईडी:* ${incidentId}

🤖 *AI ने पढ़ा और अपडेट किया:*
${filledItems.map(f => `• ${f}`).join('\n')}

⚖️ आपकी आधिकारिक पुलिस FIR शिकायत व बैंक फ्रीज निर्देश अपडेट कर दिए गए हैं।

📄 *अपडेटेड शिकायत देखें:*
${trackingLink}

💡 *सुझाव:* नई शिकायत शुरू करने के लिए कभी भी *NEW* लिखें।`
    }

    if (isEn) {
      return `✅ *Complaint (${incidentId}) Automatically Updated!*
📌 *Incident ID:* ${incidentId}

🤖 *AI Understood & Applied:*
${filledItems.map(f => `• ${f}`).join('\n')}

⚖️ Your official FIR draft and bank freeze instructions have been updated with these details.

📄 *View Updated Complaint:*
${trackingLink}

💡 *Tip:* To start a brand new complaint anytime, reply *NEW*.`
    }

    // Regional languages
    const meta = LANGUAGE_MAP[lang]
    return `✅ *Complaint (${incidentId}) Updated / ${meta?.nativeName || ''}*
📌 *Incident ID:* ${incidentId}

🤖 *AI Update Applied:*
${filledItems.map(f => `• ${f}`).join('\n')}

⚖️ FIR Draft & Bank freeze dossier synchronized.

📄 *View Updated Dossier:*
${trackingLink}

💡 *Tip:* Reply *NEW* anytime to start another complaint.`
  }

  // Generic note recorded
  if (isHi) {
    return `✅ *अतिरिक्त जानकारी पुरानी शिकायत (${incidentId}) से जोड़ दी गई।*
आपकी जानकारी घटना आईडी *${incidentId}* में दर्ज कर ली गई है।

📄 *अपडेटेड केस देखें:*
${trackingLink}

💡 *सुझाव:* नई शिकायत शुरू करने के लिए *NEW* लिखें।`
  }

  return `✅ *Update Recorded on Complaint (${incidentId}).*
Your note has been attached to Incident ID *${incidentId}*.

📄 *Track Case:*
${trackingLink}

💡 *Tip:* To start a brand new complaint anytime, reply *NEW*.`
}
